/**
 * Small CSV parser for imports (customers, etc.). Handles quoted fields,
 * commas and newlines inside quotes, doubled quotes, CRLF and a BOM, which
 * covers what Excel, Google Sheets, ServiceM8 and Tradify exports produce.
 */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let field = ''
  let inQuotes = false
  const s = text.replace(/^﻿/, '')

  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (inQuotes) {
      if (c === '"') {
        if (s[i + 1] === '"') {
          field += '"'
          i++
        } else {
          inQuotes = false
        }
      } else {
        field += c
      }
      continue
    }
    if (c === '"') inQuotes = true
    else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && s[i + 1] === '\n') i++
      row.push(field)
      field = ''
      if (row.some((v) => v.trim() !== '')) rows.push(row)
      row = []
    } else field += c
  }
  row.push(field)
  if (row.some((v) => v.trim() !== '')) rows.push(row)
  return rows
}

/** Lower-case, letters and digits only: "E-mail Address" → "emailaddress". */
export const normaliseHeader = (h: string) => h.toLowerCase().replace(/[^a-z0-9]/g, '')
