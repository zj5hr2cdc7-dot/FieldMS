#!/usr/bin/env node
/**
 * Generate supabase/VERIFY_SCHEMA.sql and supabase/VERIFY_COMPACT.sql.
 *
 *   npm run build:verify
 *
 * WHY THIS EXISTS
 *   VERIFY_SCHEMA.sql used to carry a hand-copied list of 47 objects and 206
 *   columns. A hand-copied list is a snapshot of what the code needed on the
 *   day someone copied it; the moment a query changes, the SQL check quietly
 *   goes stale and starts passing things it should catch. It is generated now,
 *   from the same scanner `npm run doctor` uses.
 *
 *   Regenerate it whenever queries change. It is fast and it is the only thing
 *   keeping the two checks honest with each other.
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { scanSchemaUsage, dropStorageBuckets } from './lib/scan-schema.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC_DIRS = ['app', 'lib', 'components', 'utils', 'hooks', 'context']

// Views cannot be told from tables by scanning, so the few we have are named.
const VIEWS = new Set(['compliance_register', 'customer_marketing_list'])

// Functions the app or its RLS policies call.
const FUNCTIONS = [
  'create_tenant_with_owner', 'next_document_number', 'set_updated_at',
  'is_office', 'is_owner', 'is_member', 'techs_see_all', 'my_role',
  'bump_asset_test_dates',
]

// ── Collect source ──────────────────────────────────────────
const files = []
const walk = (dir) => {
  let entries
  try { entries = readdirSync(dir) } catch { return }
  for (const entry of entries) {
    if (entry === 'node_modules' || entry.startsWith('.')) continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full)
    else if (/\.(ts|tsx|mjs|js)$/.test(entry)) files.push(full)
  }
}
for (const d of SRC_DIRS) walk(join(ROOT, d))

const sources = files.map((f) => readFileSync(f, 'utf-8'))
const required = scanSchemaUsage(sources)
const buckets = dropStorageBuckets(required, sources)

// ── Emit the expected list ──────────────────────────────────
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`
const rows = [...required.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([table, cols]) => {
    const kind = VIEWS.has(table) ? 'view' : 'table'
    const list = [...cols].sort()
    const arr = list.length
      ? `ARRAY[${list.map(lit).join(', ')}]::text[]`
      : `ARRAY[NULL]::text[]`
    return `    (${lit(table)}, ${lit(kind)}, ${arr})`
  })

const totalCols = [...required.values()].reduce((n, s) => n + s.size, 0)

const header = `-- ============================================================
-- FieldMS schema verification.
--
-- READ ONLY. Creates nothing, changes nothing, deletes nothing.
--
-- GENERATED FILE — do not edit by hand.
--   Produced by scripts/build-verify-sql.mjs from the same scanner that
--   backs \`npm run doctor\`. Regenerate with:  npm run build:verify
--
-- WHY THIS EXISTS
--   The repo's migration files did not match this database. Migrations 004
--   and 006 to 021 had never been applied, so about two thirds of the tables
--   the app queries did not exist. Nothing surfaced that, because a missing
--   table makes a page render empty rather than crash.
--
--   The expected schema below was generated by scanning every .from() and
--   .select() call in the codebase: ${required.size} tables and views, ${totalCols}
--   column references. It describes what the app actually needs, not what
--   anyone assumed it needed.
--
-- HOW TO USE
--   Paste into the Supabase SQL Editor and Run.
--   Every row returned is something the app expects and cannot find.
--   NO ROWS MEANS THE DATABASE SATISFIES EVERY QUERY IN THE CODEBASE.
--
--   Run it after any migration, and before any release.
-- ============================================================

WITH expected(obj, kind, cols) AS (
  VALUES
${rows.join(',\n')}
),

-- ── Missing tables and views ────────────────────────────────
missing_objects AS (
  SELECT 1 AS sort,
         'MISSING ' || upper(e.kind) AS problem,
         e.obj AS object_name,
         NULL::text AS detail
    FROM expected e
   WHERE to_regclass('public.' || e.obj) IS NULL
),

-- ── Missing columns on objects that do exist ────────────────
missing_columns AS (
  SELECT 2 AS sort, 'MISSING COLUMN' AS problem, e.obj AS object_name, c AS detail
    FROM expected e
    CROSS JOIN LATERAL unnest(e.cols) AS c
   WHERE to_regclass('public.' || e.obj) IS NOT NULL
     AND c IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM information_schema.columns ic
        WHERE ic.table_schema = 'public'
          AND ic.table_name = e.obj
          AND ic.column_name = c
     )
),

-- ── Functions the app or its RLS policies call ──────────────
missing_functions AS (
  SELECT 3 AS sort, 'MISSING FUNCTION' AS problem, f AS object_name, NULL::text AS detail
    FROM unnest(ARRAY[${FUNCTIONS.map(lit).join(', ')}]) AS f
   WHERE NOT EXISTS (
     SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = 'public' AND p.proname = f
   )
),

-- ── Storage buckets for logos, plans and site photos ────────
missing_buckets AS (
  SELECT 4 AS sort, 'MISSING BUCKET' AS problem, b AS object_name, NULL::text AS detail
    FROM unnest(ARRAY[${buckets.sort().map(lit).join(', ')}]) AS b
   WHERE to_regclass('storage.buckets') IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM storage.buckets sb WHERE sb.id = b)
),

-- ── Tenant data with RLS switched off: a cross customer leak ─
rls_off AS (
  SELECT 5 AS sort, 'RLS DISABLED' AS problem, c.relname AS object_name,
         'tenant data readable across workspaces' AS detail
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity
     AND EXISTS (
       SELECT 1 FROM information_schema.columns ic
        WHERE ic.table_schema = 'public' AND ic.table_name = c.relname
          AND ic.column_name IN ('tenant_id','business_id')
     )
),

-- ── Child tables with RLS off ───────────────────────────────
-- A line item table usually has no tenant_id of its own; it inherits its
-- scope from a parent that does. The check above cannot see those, so this
-- one follows foreign keys instead. estimate_items, job_invoice_items and
-- form_signatures all live here: leaving RLS off on one exposes every
-- workspace's quote and invoice lines to any signed in user.
rls_off_child AS (
  SELECT DISTINCT 5 AS sort, 'RLS DISABLED' AS problem, child.relname AS object_name,
         'child of ' || parent.relname || ', which is tenant scoped' AS detail
    FROM pg_constraint fk
    JOIN pg_class child  ON child.oid  = fk.conrelid
    JOIN pg_class parent ON parent.oid = fk.confrelid
    JOIN pg_namespace n  ON n.oid = child.relnamespace
   WHERE fk.contype = 'f'
     AND n.nspname = 'public'
     AND child.relkind = 'r'
     AND NOT child.relrowsecurity
     AND EXISTS (
       SELECT 1 FROM information_schema.columns ic
        WHERE ic.table_schema = 'public' AND ic.table_name = parent.relname
          AND ic.column_name IN ('tenant_id','business_id')
     )
     AND NOT EXISTS (
       SELECT 1 FROM information_schema.columns ic
        WHERE ic.table_schema = 'public' AND ic.table_name = child.relname
          AND ic.column_name IN ('tenant_id','business_id')
     )
),

-- ── RLS on with no policies: every query silently returns none ─
rls_no_policy AS (
  SELECT 6 AS sort, 'RLS BUT NO POLICY' AS problem, c.relname AS object_name,
         'every query returns zero rows' AS detail
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relrowsecurity
     AND NOT EXISTS (
       SELECT 1 FROM pg_policies p WHERE p.schemaname = 'public' AND p.tablename = c.relname
     )
),

problems AS (
    SELECT * FROM missing_objects
    UNION ALL SELECT * FROM missing_columns
    UNION ALL SELECT * FROM missing_functions
    UNION ALL SELECT * FROM missing_buckets
    UNION ALL SELECT * FROM rls_off
    UNION ALL SELECT * FROM rls_off_child
    UNION ALL SELECT * FROM rls_no_policy
)
`

const full = header + `
SELECT problem, object_name, detail
  FROM problems
 ORDER BY sort, object_name, detail;
`

const compact = header.replace(
  '-- FieldMS schema verification.',
  '-- FieldMS schema verification — COMPACT.\n-- Identical checks, but returns ONE cell so the whole result copies in one click.'
) + `
SELECT COALESCE(
         string_agg(problem || ' | ' || object_name || COALESCE(' | ' || detail, ''),
                    E'\\n' ORDER BY sort, object_name, detail),
         'CLEAN — no problems found'
       ) AS report
  FROM problems;
`

writeFileSync(join(ROOT, 'supabase/VERIFY_SCHEMA.sql'), full)
writeFileSync(join(ROOT, 'supabase/VERIFY_COMPACT.sql'), compact)

console.log(`VERIFY_SCHEMA.sql   ${required.size} objects, ${totalCols} columns`)
console.log(`VERIFY_COMPACT.sql  same checks, single cell`)
console.log(`buckets: ${buckets.join(', ')}`)
